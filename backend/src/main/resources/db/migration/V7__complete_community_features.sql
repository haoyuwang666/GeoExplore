CREATE TABLE user_tips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    place_id BIGINT NOT NULL REFERENCES places (id) ON DELETE CASCADE,
    category VARCHAR(24) NOT NULL CHECK (
        category IN ('PHOTOGRAPHY', 'TRANSPORTATION', 'TIMING', 'SAFETY', 'GENERAL')
    ),
    body VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX user_tips_user_idx ON user_tips (user_id, created_at DESC);
CREATE INDEX user_tips_place_idx ON user_tips (place_id, created_at DESC);
