CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    country VARCHAR(80) NOT NULL,
    country_code CHAR(2) NOT NULL,
    flag VARCHAR(8) NOT NULL,
    region VARCHAR(40) NOT NULL,
    latitude NUMERIC(9, 6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    eyebrow VARCHAR(180) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    best_time VARCHAR(60) NOT NULL,
    rating NUMERIC(2, 1) NOT NULL CHECK (rating BETWEEN 0 AND 5),
    tip_count INTEGER NOT NULL DEFAULT 0 CHECK (tip_count >= 0),
    accent VARCHAR(7) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT places_name_country_unique UNIQUE (name, country)
);

CREATE INDEX places_country_idx ON places (country);
CREATE INDEX places_region_idx ON places (region);
